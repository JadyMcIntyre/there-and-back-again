async function activeWorld(page: Page, world: 'atlas' | 'bag-end' | 'bag-end-interior') {
  await expect(stage(page)).toHaveAttribute('data-active-world', world)
  await expect(stage(page)).toHaveAttribute('data-transition', 'idle')
}

